/*
 * Placeholder audio for the prototype, voiced by Kokoro (open-weight
 * text-to-speech, Apache 2.0, runs locally on CPU) and joined with ffmpeg.
 * Real recordings come from the content team; this makes the shell playable
 * with natural-sounding speech.
 *
 *   npm run audio            all files
 *   npm run audio -- part-2  only files whose name contains "part-2"
 *
 * The first run downloads the model (about 90 MB) from Hugging Face into the
 * local cache. Writes public/audio/academic-1/*.m4a and
 * src/mocks/fixtures/academic-1/audio-durations.ts
 */
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import * as path from "node:path";
import { KokoroTTS } from "kokoro-js";
import { listeningSection, listeningVoices } from "../src/mocks/fixtures/academic-1/listening";
import { speakingSection, speakingVoice } from "../src/mocks/fixtures/academic-1/writing-speaking";

const ROOT = path.resolve(import.meta.dirname, "..");
const TMP = mkdtempSync(path.join(tmpdir(), "bw-audio-"));
const ONLY = process.argv[2];
const RATE = 24000; // Kokoro's output sample rate
const DURATIONS = path.join(ROOT, "src/mocks/fixtures/academic-1/audio-durations.ts");

const tts = await KokoroTTS.from_pretrained("onnx-community/Kokoro-82M-v1.0-ONNX", { dtype: "q8", device: "cpu" });

/** Keep durations of files we are not regenerating this run. */
const durations: Record<string, number> = existsSync(DURATIONS)
  ? JSON.parse(readFileSync(DURATIONS, "utf8").replace(/^[\s\S]*?= /, "").replace(/;\s*$/, ""))
  : {};

/**
 * Text as it should be spoken. Spelled-out words ("T-I-L-B-R-O-O-K") become
 * separate letters with short pauses, so each letter is clearly audible.
 * The transcript shown to learners keeps the original text.
 */
export function forSpeech(text: string): string {
  return text.replace(/\b[A-Z](?:-[A-Z]){2,}\b/g, (m) => m.split("-").join(", "));
}

let n = 0;
async function speak(voice: string, text: string): Promise<string> {
  const file = path.join(TMP, `line-${n++}.wav`);
  const audio = await tts.generate(forSpeech(text), { voice: voice as never, speed: 1 });
  await audio.save(file);
  return file;
}

function silence(seconds: number): string {
  const file = path.join(TMP, `gap-${seconds}.wav`);
  if (!existsSync(file))
    execFileSync("ffmpeg", ["-y", "-loglevel", "error", "-f", "lavfi", "-i", `anullsrc=r=${RATE}:cl=mono`, "-t", String(seconds), file]);
  return file;
}

function concat(files: string[], out: string) {
  mkdirSync(path.dirname(out), { recursive: true });
  const list = path.join(TMP, `${path.basename(out)}.txt`);
  writeFileSync(list, files.map((f) => `file '${f}'`).join("\n"));
  execFileSync("ffmpeg", [
    "-y", "-loglevel", "error", "-f", "concat", "-safe", "0", "-i", list,
    "-ar", String(RATE), "-ac", "1", "-c:a", "aac", "-b:a", "64k", out,
  ]);
}

function duration(file: string): number {
  const s = execFileSync("ffprobe", ["-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", file]).toString();
  return Math.round(Number(s) * 10) / 10;
}

const want = (src: string) => !ONLY || src.includes(ONLY);

/* Listening: one file per part, each speaker in their own voice, short gaps between turns. */
for (const part of listeningSection.parts) {
  if (!part.audio || !want(part.audio.src)) continue;
  const files: string[] = [];
  for (const line of part.audio.transcript) {
    files.push(await speak(listeningVoices[line.speaker] ?? "bm_george", line.text));
    // The real test gives about 30 seconds to read questions; shortened for the prototype.
    const readingPause = line.speaker === "Narrator" && /time to look|have some time|check your answers/i.test(line.text);
    files.push(silence(readingPause ? 6 : line.speaker === "Narrator" ? 1 : 0.45));
  }
  const out = path.join(ROOT, "public", part.audio.src);
  concat(files, out);
  durations[part.audio.src] = duration(out);
  console.log(part.audio.src, durations[part.audio.src], "s");
}

/* Speaking: one file per examiner line. */
for (const part of speakingSection.parts) {
  const qs = [part.speaking?.intro, ...(part.speaking?.questions ?? [])].filter(Boolean) as { text: string; audio: string }[];
  for (const q of qs) {
    if (!want(q.audio)) continue;
    const out = path.join(ROOT, "public", q.audio);
    concat([await speak(speakingVoice, q.text), silence(0.3)], out);
    durations[q.audio] = duration(out);
  }
  console.log(part.id, qs.length, "examiner lines");
}

writeFileSync(
  DURATIONS,
  `/* Generated by scripts/make-audio.ts. Seconds per audio file. */\nexport const audioDurations: Record<string, number> = ${JSON.stringify(durations, null, 2)};\n`,
);
console.log("wrote", DURATIONS);
